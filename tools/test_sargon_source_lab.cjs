/* Sargon Evidence Lab checks: source limits, empire reasoning and Lesson 4A placement. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const page=read("social-studies/sargon-source-lab.html");
assert.match(page,/Legend/);
assert.match(page,/Sumerian King List/);
assert.match(page,/1,500 years/);
assert.match(page,/simplified diagram/);
assert.match(page,/data-check-claims/);
assert.match(page,/data-check-empire/);
assert.match(page,/army or court/);
assert.match(page,/not submitted or stored online/);
assert.doesNotMatch(page,/fetch\(|localStorage|sessionStorage/);
const ctx={window:{},document:{readyState:"loading",addEventListener(){}}};
vm.runInNewContext(read("social-studies/sargon-source-lab.js"),ctx,{filename:"sargon-source-lab.js"});
const L=ctx.window.SargonSourceLab;
assert.equal(L.claims.length,5);
const good={ "king-list":"source", ishtar:"claim", akkad:"uncertain", stele:"claim", head:"uncertain" };
assert.equal(L.claimFeedback({}).score.complete,false);
assert.equal(L.claimFeedback(good).score.correct,5);
assert.equal(L.claimFeedback({...good,ishtar:"source"}).score.correct,4);
assert.equal(L.empire.length,8);
const tools={army:"tool",governors:"tool",language:"tool",religion:"tool",trade:"tool",rebellion:"pressure",drought:"pressure",gutians:"pressure"};
assert.equal(L.empireFeedback(tools).score.correct,8);
assert.match(L.empireFeedback(tools).details,/debated explanation/);
assert.match(L.buildAdvice("governors","They can represent the king in distant cities."),/trusted governors/);
assert.match(L.buildAdvice("trade","short"),/Add a reason/);
assert.match(L.buildAdvice("","A long reason here"),/Choose one/);
const atlas=read("social-studies/index.html");
assert.match(atlas,/id:"l4a"[\s\S]*?activity:\{href:"sargon-source-lab\.html"/);
console.log("Sargon Evidence Lab passed: source classifications, empire tool/pressure model, advice scaffold and Lesson 4A integration.");
