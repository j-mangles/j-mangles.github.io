/* Grade 8 Cells · microscope model invariants and wiring regression test. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const source=fs.readFileSync(path.join(root,"science/microscope-studio.js"),"utf8");
new vm.Script(source,{filename:"microscope-studio.js"});
const window={HUB:{lessonTools:{}}};
vm.runInNewContext(source,{window,console},{timeout:3000});
assert.equal(typeof window.HUB.lessonTools["cells/theory"],"function","Cell Theory lesson must mount microscope");
const model=window.MicroscopeStudio;
assert.equal(model.total(4),40);
assert.equal(model.total(10),100);
assert.equal(model.total(40),400);
assert.equal(model.fov(4),4500);
assert.equal(model.fov(10),1800);
assert.equal(model.fov(40),450);
assert.equal(model.fov(4)/model.fov(40),10,"Higher power narrows field by inverse objective ratio");
assert.equal(model.SPECIMENS.onion.size,200);
assert.equal(model.SPECIMENS.cheek.size,65);
assert.equal(model.SPECIMENS.blood.size,8);
assert.ok(model.fov(40)<model.fov(10));
const html=fs.readFileSync(path.join(root,"science/index.html"),"utf8");
const library=fs.readFileSync(path.join(root,"science/labs.html"),"utf8");
assert.ok(html.includes('src="microscope-studio.js'));
assert.ok(library.includes('"Microscope Investigation Studio"'));
assert.ok(library.includes('"cells/theory"'));
assert.ok(source.includes("No observations yet."));
assert.ok(source.includes("not automatically saved or submitted"));
console.log("Microscope unit tests passed: lenses, magnification, inverse FOV calibration, three specimen models, current-unit integration.");
