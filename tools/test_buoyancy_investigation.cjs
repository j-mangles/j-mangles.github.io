/* Grade 8 buoyancy model correctness and feature wiring. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),js=fs.readFileSync(path.join(root,"science/buoyancy-investigation.js"),"utf8");
new vm.Script(js,{filename:"buoyancy-investigation.js"});
const window={HUB:{lessonTools:{"matter/density":()=>{}}},confirm(){return true;}};
vm.runInNewContext(js,{window,console},{timeout:3000});
const m=window.BuoyancyModel;
assert.ok(m);
assert.equal(m.result(50,100,"water").state,"float");
assert.equal(m.result(50,100,"water").submerged,.5);
assert.equal(m.result(100,100,"water").state,"neutral");
assert.equal(m.result(150,100,"water").state,"sink");
assert.equal(m.result(100,100,"oil").state,"sink");
assert.equal(m.result(100,100,"glycerin").state,"float");
assert.ok(Math.abs(m.result(100,100,"glycerin").submerged-1/1.26)<1e-10);
assert.equal(m.result(92,100,"oil").state,"neutral");
assert.throws(()=>m.result(0,100,"water"));
assert.throws(()=>m.result(100,-10,"water"));
assert.throws(()=>m.result(100,100,"unknown"));
assert.deepEqual(Object.keys(m.liquids).sort(),["glycerin","oil","salt","water"]);
assert.ok(m.objects.steel.density>m.objects.wood.density);
const html=fs.readFileSync(path.join(root,"science/index.html"),"utf8");
assert.ok(html.includes("buoyancy-investigation.js"));
assert.ok(html.includes("buoyancy-investigation.css"));
const data={};new Function("window",fs.readFileSync(path.join(root,"science/data.js"),"utf8"))(data);
assert.equal(data.HUB.units.find(u=>u.id==="matter").status,"soon","Future unit stays unreleased");
assert.equal(typeof window.HUB.lessonTools["matter/density"],"function");
console.log("Buoyancy unit tests passed: liquids, float/sink/neutral, submerged fractions, invalid inputs and release gate.");
