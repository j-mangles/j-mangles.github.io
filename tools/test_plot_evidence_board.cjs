/* Grade 8 ELA: six stage plot board with editable evidence and tension chart. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const ctx={window:{HUB:{subject:"ela",tools:{stories:()=>{}},lessonTools:{}}}};
const old=ctx.window.HUB.tools.stories;
vm.runInNewContext(read("ela/plot-evidence-board.js"),ctx,{filename:"ela/plot-evidence-board.js"});
const P=ctx.window.PlotEvidenceCore;
assert.equal(ctx.window.HUB.tools.stories,old,"Preserve the original unit Plot Arc explorer");
assert.equal(typeof ctx.window.HUB.lessonTools["stories/plot"],"function");
assert.deepEqual(Array.from(P.STAGES,x=>x.name),["Exposition","Inciting incident","Rising action","Climax","Falling action","Resolution"]);
assert.deepEqual(Array.from(P.TEXTS,x=>x.id),["snack","thankyou"]);
assert.equal(P.initial().length,6);
const a=P.initial();
assert.ok(a.every(x=>x.moment===""&&x.evidence===""&&x.tension===0));
a[3].tension=9;a[3].moment="Sample specific turning point";a[3].evidence="Student cited specific moment";
const g=P.graph(a);
assert.ok(g.includes("Climax 9 of 10")&&g.includes('role="img"')&&g.includes("not a fixed answer"));
assert.ok(!g.includes("NaN")&&!g.includes("undefined"));
const report=P.report("thankyou",a,"A student explanation of their interpretation");
assert.ok(report.includes("Thank You, Ma’am")&&report.includes("4. Climax")&&report.includes("My tension rating: 9/10")&&report.includes("A student explanation"));
const adversarial=P.initial();adversarial[0].moment='<img src=x onerror=alert(1)>';adversarial[0].tension='"><script>alert(1)</script>';
const chart=P.graph(adversarial);
assert.ok(!chart.includes("<script>")&&!chart.includes("<img"));
assert.ok(chart.includes("Exposition 0 of 10"));
const page=read("ela/index.html"),scripts=[...page.matchAll(/<script src="([^"]+)"/g)].map(x=>x[1]);
assert.ok(scripts.includes("plot-evidence-board.js")&&scripts.indexOf("plot-evidence-board.js")<scripts.indexOf("../assets/hub.js"));
const data={window:{}};vm.runInNewContext(read("ela/data.js"),data);
assert.ok(data.window.HUB.units.some(u=>u.id==="stories"&&u.lessons.some(l=>l.id==="plot"&&l.title==="Plot Structure")));
assert.ok(read("index.html").includes('href="ela/#stories/plot"'));
console.log("ELA Plot Evidence Board: six stages, editable response report, safe graph, source unit and original tool preserved.");
