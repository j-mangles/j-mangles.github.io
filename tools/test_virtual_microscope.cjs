/* Virtual Microscope: scientific assumptions, rendering registration, and lesson directory checks. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(root,"science/virtual-microscope.js"),"utf8");
new vm.Script(js,{filename:"virtual-microscope.js"});
const win={HUB:{lessonTools:{"cells/theory":()=>{}}},confirm(){return true;}};
vm.runInNewContext(js,{window:win,console},{timeout:3000});
const core=win.VirtualMicroscopeCore;
assert.equal(typeof win.HUB.lessonTools["cells/theory"],"function");
assert.equal(core.ocular,10);
assert.deepEqual(Array.from(core.objectives),[4,10,40]);
assert.equal(core.total(4),40);
assert.equal(core.total(10),100);
assert.equal(core.total(40),400);
assert.equal(core.fieldUm(4),4500);
assert.equal(core.fieldUm(10),1800);
assert.equal(core.fieldUm(40),450);
assert.equal(core.estimate(450,5),90);
assert.equal(core.countAcross("onion",40),450/110);
assert.deepEqual(JSON.parse(JSON.stringify(core.countFeedback("onion",40,4))),{expected:4.1,outside:false});
assert.equal(core.countFeedback("onion",40,20).outside,true,"far-off estimates should get a non-grading comparison hint");
assert.ok(core.countAcross("cheek",4)>core.countAcross("cheek",40));
assert.ok(Number.isNaN(core.estimate(450,0)));
assert.ok(Object.keys(core.specimens).length>=3);
assert.ok(core.specimens.onion.note.includes("chloroplasts"));
const science=fs.readFileSync(path.join(root,"science/index.html"),"utf8");
assert.ok(science.includes("virtual-microscope.js"));
assert.ok(science.includes("virtual-microscope.css"));
assert.ok(js.includes("../computer-class/#science-microscope-evidence"),"Independent follow-up lesson linked");
const library=fs.readFileSync(path.join(root,"science/labs.html"),"utf8");
assert.match(library,/Virtual Microscope Investigation/);
assert.match(library,/cells\/theory/);
assert.ok(!/localStorage|fetch\s*\(/.test(js),"No private data stored or transmitted");
assert.ok(!js.includes('"Approx. "+rnd(core.countAcross(name,obj))'),"Do not reveal the illustrated count before student measurement");
console.log("Microscope model passed: magnifications, field widths, approximate cell sizes, lesson registration and local-only data.");
