/* Grade 8 matter: buoyancy model, density ratios and safe lesson composition. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const src=fs.readFileSync(path.join(root,"science/buoyancy-liquid-comparison.js"),"utf8");
new vm.Script(src);
const calls=[];
const HUB={lessonTools:{"matter/density":el=>calls.push(el)}},window={HUB};
vm.runInNewContext(src,{window,console},{timeout:3000});
const m=HUB.buoyancyModel.model;
assert.equal(Object.keys(HUB.buoyancyModel.FLUIDS).length,4);
assert.equal(m(120,100,"water").result,"sinks");
assert.equal(m(120,100,"syrup").result,"floats");
assert.equal(m(120,100,"oil").result,"sinks");
assert.equal(m(80,100,"oil").result,"floats");
assert.equal(m(100,100,"water").result,"neutral");
assert.ok(Math.abs(m(120,100,"syrup").submerged-120/133)<1e-10);
assert.equal(m(120,100,"water").submerged,1);
assert.equal(m(100,100,"salt").liquidDensity,1.03);
assert.throws(()=>m(0,100,"water"));
assert.throws(()=>m(100,0,"water"));
assert.throws(()=>m(100,100,"unknown"));
assert.equal(typeof HUB.lessonTools["matter/density"],"function");
assert.ok(src.includes('previous(old)'),"Previously built Matter visual remains mounted");
const html=fs.readFileSync(path.join(root,"science/index.html"),"utf8");
assert.ok(html.indexOf("matter-visuals.js")<html.indexOf("buoyancy-liquid-comparison.js"));
assert.ok(html.indexOf("buoyancy-liquid-comparison.js")<html.indexOf("../assets/hub.js"));
const labLibrary=fs.readFileSync(path.join(root,"science/labs.html"),"utf8");
assert.ok(labLibrary.includes('"Liquid Buoyancy Comparison"'));
assert.ok(labLibrary.includes('"Coming soon"'),"Matter stays unreleased");
console.log("Buoyancy tests passed: four liquids, density outcomes, partial submersion, model errors, and legacy tool composition.");
