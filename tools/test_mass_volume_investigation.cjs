/* Scientific model regression tests — mass-versus-volume slope and release gate. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const source=fs.readFileSync(path.join(root,"science/mass-volume-investigation.js"),"utf8");
new vm.Script(source,{filename:"mass-volume-investigation.js"});
const win={HUB:{lessonTools:{"matter/density":()=>{}}}};
vm.runInNewContext(source,{window:win,console},{timeout:3000});
const m=win.MassVolumeCore;
assert.equal(typeof win.HUB.lessonTools["matter/density"],"function");
assert.equal(m.measure("wood",40).mass,28);
assert.equal(m.measure("plastic",40).mass,48);
assert.equal(m.measure("metal",40).mass,108);
assert.throws(()=>m.measure("wood",13));
assert.throws(()=>m.measure("not a material",20));
assert.throws(()=>m.slope([]));
assert.throws(()=>m.slope([{volume:20,mass:14}]),/Two or more/);
assert.throws(()=>m.slope([{volume:20,mass:-3},{volume:40,mass:28}]));
const rows=[m.measure("wood",20),m.measure("wood",40),m.measure("plastic",20),m.measure("plastic",40),m.measure("metal",20),m.measure("metal",40)];
assert.equal(m.slope(m.observations(rows,"wood")),.7);
assert.equal(m.slope(m.observations(rows,"plastic")),1.2);
assert.equal(m.slope(m.observations(rows,"metal")),2.7);
assert.equal(m.complete(rows),true);
const svg=m.portableSvg(rows);
assert.match(svg,/xmlns="http:\/\/www.w3.org\/2000\/svg"/);
assert.match(svg,/Volume \(cm³\)/);
assert.match(svg,/Mass \(g\)/);
assert.match(svg,/<style>text\{/);
assert.equal((svg.match(/<circle /g)||[]).length,6);
assert.equal(m.complete(rows.slice(0,5)),false);
assert.equal(m.classify(.7),"float");
assert.equal(m.classify(1),"neutral");
assert.equal(m.classify(2.7),"sink");
assert.throws(()=>m.classify(0));
const html=fs.readFileSync(path.join(root,"science/index.html"),"utf8");
assert.match(html,/mass-volume-investigation\.js/);
assert.ok(html.indexOf('buoyancy-investigation.js')<html.indexOf('mass-volume-investigation.js'),"Must extend existing density lab after buoyancy");
const dataWindow={};vm.runInNewContext(fs.readFileSync(path.join(root,"science/data.js"),"utf8"),{window:dataWindow});
assert.equal(dataWindow.HUB.units.find(u=>u.id==="matter").status,"soon");
assert.ok(!/localStorage|fetch\s*\(/.test(source),"Model must not transmit or persist student data");
console.log("Mass–Volume core passed: measurements, least-squares density slope, invalid inputs, predictions, lesson wiring and release gate.");