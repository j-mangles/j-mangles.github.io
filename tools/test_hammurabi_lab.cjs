/* Hammurabi Court Lab regression checks: source accuracy, claim scaffolding and lesson placement. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const page=read("social-studies/hammurabi-court-lab.html");
assert.match(page,/data-reveal/g);
assert.equal((page.match(/data-case-card/g)||[]).length,3);
assert.match(page,/Law 230/);
assert.match(page,/data-eye-check/);
assert.match(page,/class="workbox" data-eye-card/);
assert.match(page,/not submitted or saved online/);
assert.doesNotMatch(page,/fetch\(|localStorage|sessionStorage/);
const ctx={window:{},document:{readyState:"loading",addEventListener(){}}};
vm.runInNewContext(read("social-studies/hammurabi-lab.js"),ctx,{filename:"hammurabi-lab.js"});
const L=ctx.window.HammurabiCourtLab;
assert.equal(L.cases.length,3);
assert.deepEqual(Array.from(L.cases,x=>x.law),["Law 1","Law 229","Law 218"]);
assert.ok(L.cases[1].source.includes("builder build a house"));
assert.ok(L.cases[1].reading.includes("discourage unsafe building"));
assert.deepEqual(Array.from(L.classes,x=>x.law),["196","198","199"]);
assert.ok(L.classes[2].recipient.includes("owner"));
assert.equal(L.buildArgument("order",["law1"]).ok,false);
const claim=L.buildArgument("fairness",["law1","laws196199"]);
assert.equal(claim.ok,true);
assert.match(claim.text,/more concerned with fairness/);
assert.match(claim.text,/Law 1/);
assert.match(claim.text,/Laws 196, 198 and 199/);
assert.equal(L.buildArgument("order",["law1","law1"]).ok,false,"duplicate evidence should not satisfy two-source requirement");
const atlas=read("social-studies/index.html");
assert.match(atlas,/id:"l4b"[\s\S]*?activity:\{href:"hammurabi-court-lab\.html"/);
console.log("Hammurabi Court Lab passed: three reveal-after-attempt cases, class comparison, claim scaffold, privacy and Lesson 4B integration.");
