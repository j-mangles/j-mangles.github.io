/* Structure, content and UI smoke tests for Science organization diagram. */
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(root,"science/organization-explorer.js"),"utf8");
const H={subject:"sci",lessonTools:{}};
vm.runInNewContext(js,{window:{HUB:H}},{filename:"organization-explorer.js",timeout:2000});
assert.equal(typeof H.lessonTools["cells/levels"],"function");
assert.deepEqual(Array.from(H.organizationModel.stages,s=>s.name),["Cell","Tissue","Organ","Organ system","Organism"]);
assert.match(H.organizationModel.stages[2].meaning,/several tissue types/);
const index=fs.readFileSync(path.join(root,"science/index.html"),"utf8");
assert.ok(index.indexOf('src="organization-explorer.js"')>=0);
assert.ok(index.indexOf('src="organization-explorer.js"')<index.indexOf('src="../assets/hub.js"'));
const node=(dataset={})=>({dataset,innerHTML:"",textContent:"",value:"",attrs:{},setAttribute(k,v){this.attrs[k]=v;}});
const nodes=new Map(),pills=Array.from({length:5},(_,i)=>node({level:String(i)}));
const selects=Array.from({length:5},(_,i)=>node({place:String(i)}));
const el={innerHTML:"",querySelector(k){if(!nodes.has(k))nodes.set(k,node());return nodes.get(k);},querySelectorAll(k){
 if(k==="#org-pills [data-level]")return pills;
 if(k==="#org-order [data-place]")return selects;
 throw Error("Unexpected selector: "+k);
}};
H.lessonTools["cells/levels"](el);
const $=q=>el.querySelector(q);
assert.match(el.innerHTML,/Levels of Organization Explorer/);
assert.match($("#org-svg").innerHTML,/<svg|<rect/);
assert.match($("#org-svg").attrs["aria-label"],/not to scale/);
pills[2].onclick();
assert.match($("#org-example").textContent,/Heart/);
assert.match($("#org-svg").attrs["aria-label"],/Highlighted: Organ/);
selects.forEach((s,i)=>s.value=String(i));
$("#org-check").onclick();assert.match($("#org-feedback").textContent,/Correct/);
selects[0].value="2";selects[2].value="0";
$("#org-check").onclick();assert.match($("#org-feedback").textContent,/Not yet/);
selects[1].value="2";
$("#org-check").onclick();assert.match($("#org-feedback").textContent,/exactly once/);
selects[1].value="";
$("#org-check").onclick();assert.match($("#org-feedback").textContent,/all five/);
$("#org-clear").onclick();assert.match($("#org-feedback").textContent,/cleared/);
console.log("Science organization explorer passed: five-stage diagram, concept text, ordering, checks and script integration.");